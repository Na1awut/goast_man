// Generate the reviewed import without touching the demo seed or other stores.
// Run: node supabase/data/generate-loongnoom.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const data = JSON.parse(readFileSync(new URL('./loongnoom_square.json', import.meta.url), 'utf8'));
const s = data.store;
const items = data.sections.flatMap((section) => section.items.map((item) => ({
  ...item, category: section.category, description: item.description ?? section.description ?? ''
})));
assert.equal(s.zone, 'cb1');
assert.equal(items.length, 87);
assert.equal(new Set(items.map((i) => i.code)).size, items.length);
assert.equal(new Set(items.map((i) => i.name)).size, items.length);
for (const i of items) {
  assert.match(i.code, /^[a-z0-9-]+$/);
  assert(i.name.length > 0 && i.name.length <= 80);
  assert(i.category.length <= 40 && i.description.length <= 200);
  assert(Number.isInteger(i.price) && i.price > 0 && i.price <= 2000);
}
const q = (value) => value === null ? 'null' : typeof value === 'string'
  ? `'${value.replaceAll("'", "''")}'` : String(value);
const values = (row) => `(${row.map(q).join(', ')})`;
const sql = `-- Generated by generate-loongnoom.mjs from loongnoom_square.json.
-- Apply 20261012000000_cb1_zone.sql in a separate transaction first.
-- Source: ${data.source}; coffee options and CB1 confirmed by the user.
-- New store stays hidden/closed, matching team-console creation defaults.
-- Reapplying preserves team edits, availability, photos and visibility.
begin;
do $import$
declare
  stores_added integer;
  menus_added integer;
begin
  insert into public.stores
    (id, zone, name, category, description, image_url, logo_url, banner_url, is_partner, hidden, is_open, lock)
  values ${values([s.id, s.zone, s.name, s.category, s.description, s.imageUrl, s.logoUrl, s.bannerUrl, s.isPartner, s.hidden, s.isOpen, s.lock])}
  on conflict (id) do nothing;
  get diagnostics stores_added = row_count;

  insert into public.menu_items
    (id, store_id, name, price, description, image_url, category, is_available, sort)
  values
${items.map((i, index) => '    ' + values([`${s.id}-${i.code}`, s.id, i.name, i.price, i.description, '', i.category, true, index + 1])).join(',\n')}
  on conflict (id) do nothing;
  get diagnostics menus_added = row_count;

  if stores_added > 0 or menus_added > 0 then
    insert into public.admin_log (actor_name, action, target_type, target_id, target_label, detail)
    values ('SQL import (Supabase CLI)', 'STORE_IMPORTED', 'store', ${q(s.id)}, ${q(s.name)},
      jsonb_build_object('source', ${q(data.source)}, 'stores_added', stores_added,
        'menus_added', menus_added, 'location_confirmed', 'CB1', 'coffee_options', 'iced/blended'));
  end if;
end
$import$;
commit;
`;
writeFileSync(new URL('./loongnoom_square.sql', import.meta.url), sql, 'utf8');
console.log(`Generated ${items.length} menu items in ${data.sections.length} categories.`);
